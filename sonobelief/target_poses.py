"""Candidate probe poses with frozen target labels, and per-patient ranking metrics of a scorer.

Banks (generated by sonobelief.target): "dense" = subcostal bank aimed at the GB (train only), "blind" = GB-blind bank
(8000 poses per study, the evaluation candidates). Only studies with an applicable, available target are used.
"""
import math
import os

import numpy as np
import pandas as pd
import torch

from sonobelief import paths
from sonobelief.geometry import canonical, plane_rot_dist
from sonobelief.metrics import auroc, avg_precision
from sonobelief.paths import ANATOMY

TD = paths.WORK
BANKS = {"dense": os.path.join(TD, "gb_target_subcostal"), "blind": os.path.join(TD, "target_bank_blind")}


class PoseSet:
    """Labelled poses of the chosen banks for the applicable studies of a split."""

    def __init__(self, V, banks, state):
        summ = pd.read_csv(os.path.join(TD, "gb_target_summary.csv")).set_index("study")
        pose, y, pat, skin, rot = [], [], [], [], []
        self.T_skin, self.T_rot, self.patients = {}, {}, []
        for i, sid in enumerate(V.studies):
            if not bool(summ.loc[sid, "applicable"]):
                continue
            lc = np.load(os.path.join(ANATOMY, f"{sid}.npz"))["liver_c"]
            Ts, Tr = [], []
            for b in ("dense", "blind"):
                path = os.path.join(BANKS[b], f"{sid}.npz")
                if not os.path.exists(path):
                    continue
                d = np.load(path)
                beam = torch.from_numpy(d["beam"]).float().cuda()
                lat, _ = canonical(beam, torch.from_numpy(d["lateral"]).float().cuda())
                inT = torch.from_numpy(d["in_T"].astype(bool)).cuda()
                R = torch.stack([lat, beam, torch.cross(lat, beam, dim=-1)], -1)
                sk = torch.from_numpy(d["skin"]).float().cuda()
                Ts.append(sk[inT]); Tr.append(R[inT])
                if b in banks:
                    ap = torch.from_numpy(d["apex"]).float().cuda()
                    pose.append(torch.cat([(ap - torch.from_numpy(lc).float().cuda()) / 100, beam, lat], 1))
                    y.append(inT.float()); pat.append(torch.full((len(inT),), i, device="cuda"))
                    skin.append(sk); rot.append(R)
            self.T_skin[i], self.T_rot[i] = torch.cat(Ts), torch.cat(Tr)
            self.patients.append(i)
        self.pose, self.y, self.pat = torch.cat(pose), torch.cat(y), torch.cat(pat)
        self.skin, self.rot = torch.cat(skin), torch.cat(rot)
        self.available = {i: bool(summ.loc[V.studies[i], "available"]) for i in self.patients}
        self.studies = V.studies
        geo = torch.zeros(len(V.studies), 7, device="cuda")
        iu = torch.triu_indices(3, 3)
        for i in self.patients:
            d = np.load(os.path.join(BANKS["dense"], f"{V.studies[i]}.npz"))
            a = torch.from_numpy(d["gb_axes"][0]).float().cuda()
            geo[i, :6] = torch.outer(a, a)[iu[0], iu[1]]
            geo[i, 6] = float(d["gb_length"]) / 100
        if state == "zl":
            self.state = V.zl
        elif state == "zl_rgb":
            self.state = torch.cat([V.zl, V.r_gb / 100], 1)
        elif state == "gb":
            self.state = torch.cat([V.r_gb / 100, geo], 1)
        elif state == "zl_gb":
            self.state = torch.cat([V.zl, V.r_gb / 100, geo], 1)
        else:
            self.state = torch.zeros(len(V.studies), 1, device="cuda")

    def __len__(self):
        return len(self.y)


@torch.no_grad()
def predict(model, D, state, chunk=65536):
    model.eval()
    out = [model(state[D.pat[i:i + chunk]], D.pose[i:i + chunk, None])[:, 0, 0].float() for i in range(0, len(D), chunk)]
    model.train()
    return torch.cat(out)


def dist_to_T(D, p, idx):
    """Pose distance (skin mm + rotation deg mod flip) of candidates idx of patient p to the nearest known T pose."""
    if len(D.T_skin[p]) == 0:
        return torch.full((len(idx),), float("nan"), device="cuda")
    return torch.stack([((D.T_skin[p] - D.skin[j]).norm(dim=1) + plane_rot_dist(D.rot[j], D.T_rot[p])).min() for j in idx])


def evaluate(s, D):
    """Per-patient ranking metrics of scores s (len(D)) on the bank of D."""
    rows = []
    for p in D.patients:
        if not D.available[p]:
            continue
        m = (D.pat == p).nonzero()[:, 0]
        sp, yp = s[m], D.y[m]
        n, npos = len(yp), int(yp.sum())
        o = torch.argsort(sp, descending=True)
        top = m[o[:10]]
        dtop = dist_to_T(D, p, top)
        r = {"study": D.studies[p], "n": n, "n_pos": npos, "prevalence": npos / n,
             "top1_dist": dtop[0].item(), "top10_best_dist": dtop.min().item()}
        if npos > 0:
            r.update(auroc=auroc(sp, yp), auprc=avg_precision(sp, yp), recall1=float(yp[o[0]] > 0),
                     recall10=float(yp[o[:10]].max() > 0),
                     recall10_random=1 - math.exp(sum(math.log((n - npos - k) / (n - k)) for k in range(10))))
        rows.append(r)
    return rows


def summarise(rows):
    df = pd.DataFrame(rows)
    pos = df[df.n_pos > 0]
    return {"patients": len(df), "patients_with_pos": len(pos), "auroc": pos.auroc.mean(), "auprc": pos.auprc.mean(),
            "auprc_random": pos.prevalence.mean(), "recall1": pos.recall1.mean(), "recall1_random": pos.prevalence.mean(),
            "recall10": pos.recall10.mean(), "recall10_random": pos.recall10_random.mean(),
            "top1_dist_median": df.top1_dist.median(), "top1_dist_mean": df.top1_dist.mean(),
            "top10_best_dist_median": df.top10_best_dist.median()}


@torch.no_grad()
def random_dist(D, gen, n=200):
    """Median over patients of the expected distance to T of a random candidate."""
    out = []
    for p in D.patients:
        if not D.available[p]:
            continue
        m = (D.pat == p).nonzero()[:, 0]
        j = m[torch.randint(len(m), (n,), device="cuda", generator=gen)]
        out.append(dist_to_T(D, p, j).mean().item())
    return float(np.median(out))


def fmt(name, r):
    return (f"{name:14s} AUROC {r['auroc']:.3f} | AUPRC {r['auprc']:.3f} (rand {r['auprc_random']:.3f}) | R@1 {r['recall1']:.2f} "
            f"(rand {r['recall1_random']:.2f}) | R@10 {r['recall10']:.2f} (rand {r['recall10_random']:.2f}) | top-1 dist med "
            f"{r['top1_dist_median']:.1f} | best of top-10 med {r['top10_best_dist_median']:.1f}  [{r['patients_with_pos']}/{r['patients']} pts]")


def evaluate_fast(s, D):
    """Per-patient AUROC / AUPRC (training log and model selection)."""
    out = []
    for p in D.patients:
        m = D.pat == p
        if 0 < D.y[m].sum() < m.sum():
            out.append({"auroc": auroc(s[m], D.y[m]), "auprc": avg_precision(s[m], D.y[m])})
    return out
